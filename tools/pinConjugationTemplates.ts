// Pins the `{{It-conj}}` calls rule `it-regular-conjugation/v1` reads (#838).
//
//   pnpm exec tsx tools/pinConjugationTemplates.ts <it-extract.jsonl.gz> <itwiktionary-20260701-pages-articles.xml.bz2> \
//     > src/italian/conjugationTemplateCalls.ts
//
// It reads every Italian verb record of the archive and keeps the pronominal
// verbs the base-verb route leaves without a table: no record of the word
// fills a cell, and no base verb record has a table. For each, it looks up the
// Appendice pages that conjugate the word and each of its base verbs
// (`Appendice:Coniugazioni/Italiano/pentirsi`, `…/pentire`) in the dump the
// archive was built from, checked against its published SHA-1, and writes the
// first `{{It-conj}}` call on each page, verbatim, with the page's revision.
// It changes nothing else; the module it writes is never edited by hand.

import { ARCHIVE_DUMP, APPENDIX_NAMESPACE, VerifiedDump } from "../src/source/wiktionaryDump.js";
import { pronominalVerb } from "../src/italian/pronominalConjugation.js";
import { conjugationPageOf, type PinnedTemplateCall } from "../src/italian/regularConjugation.js";
import { baseOf, fillsCell, readVerbs } from "./pronominalArchive.js";

const [archive, dumpPath] = process.argv.slice(2);
if (!archive || !dumpPath) throw new Error("usage: tools/pinConjugationTemplates.ts <it-extract.jsonl.gz> <itwiktionary-20260701-pages-articles.xml.bz2>");

const verbs = await readVerbs(archive);
const wanted = new Set<string>();
for (const [word, records] of verbs) {
  const verb = pronominalVerb(word);
  if (verb === undefined || records.some(fillsCell) || baseOf(verbs, verb).base !== undefined) continue;
  for (const one of [word, ...verb.bases]) wanted.add(conjugationPageOf(one));
}

/** The first `{{It-conj…}}` call on a page, through its matching `}}`, or undefined. */
function firstCall(wikitext: string): string | undefined {
  const start = wikitext.search(/\{\{\s*It-conj\s*\|/u);
  if (start < 0) return undefined;
  let depth = 0;
  for (let i = start; i < wikitext.length - 1; i++) {
    const pair = wikitext.slice(i, i + 2);
    if (pair === "{{") depth++;
    else if (pair === "}}") depth--;
    else continue;
    i++;
    if (depth === 0) return wikitext.slice(start, i + 1);
  }
  return undefined;
}

const pinned: PinnedTemplateCall[] = [];
const dump = await VerifiedDump.open(dumpPath, ARCHIVE_DUMP);
try {
  for await (const page of dump.pages(APPENDIX_NAMESPACE)) {
    if (!wanted.has(page.title)) continue;
    const call = firstCall(page.wikitext);
    if (call !== undefined) pinned.push({ title: page.title, revisionId: page.revisionId, timestamp: page.timestamp, call });
  }
} finally {
  await dump.close();
}
pinned.sort((a, b) => a.title.localeCompare(b.title));

const lines = [
  "// Generated by `pnpm exec tsx tools/pinConjugationTemplates.ts` from it-0c432803 and",
  `// ${ARCHIVE_DUMP.file}: the \`{{It-conj}}\` call of each Appendice page that conjugates`,
  "// a pronominal verb the base-verb route leaves without a table, or one of its base verbs,",
  "// pinned by revision id. Rule `it-regular-conjugation/v1` reads them (#838). Never edited by hand.",
  "",
  'import type { TemplateCalls } from "./regularConjugation.js";',
  "",
  "export const CONJUGATION_TEMPLATE_CALLS: TemplateCalls = {",
  ...pinned.map((page) => `  ${JSON.stringify(page.title)}: ${JSON.stringify(page)},`),
  "};",
  "",
];
process.stdout.write(lines.join("\n"));
console.error(`pinned ${pinned.length} calls of ${wanted.size} pages looked for`);
